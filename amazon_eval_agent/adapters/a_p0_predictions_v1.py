"""Reader adapter for A P0 per-task baseline predictions (JSONL, v1).

The recovered A ``baseline_review`` directory contains ``predictions.jsonl``:
one row per ``(task_index, mode)`` with ``split``, continuous ``prediction``
and cold-start flags. It contains no labels, review text, identifiers or
prompts. B verifies the table's shape, uniqueness, ranges and split consistency
before using it as a fixed baseline comparison.

The file alone does not prove the predictions were generated by the named
algorithm. B reports it as an A-declared prediction table, not as an
independently reproduced A run.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Sequence

from ..safety import (
    MAX_BASELINE_BYTES,
    MAX_BASELINE_ROWS,
    deep_freeze,
    exact_keys,
    finite_number,
    load_jsonl_bytes,
    sha256_bytes,
)

A_P0_PREDICTIONS_ADAPTER_VERSION = "a_p0_predictions_v1.reader_v1"
BASELINE_MODES = ("global", "user", "item", "combined")
SPLITS = ("train", "validation", "test")
_FIELDS = (
    "task_index",
    "split",
    "mode",
    "prediction",
    "user_cold_start",
    "item_cold_start",
)


class BaselinePredictionsError(ValueError):
    """Safe baseline-table failure; no values are echoed."""

    def __init__(self, code: str, errors: Sequence[str] = ()):
        self.code = code
        self.errors = tuple(sorted(set(errors))) if errors else (code,)
        super().__init__(code)


@dataclass(frozen=True)
class BaselinePredictionTable:
    raw_sha256: str
    rows_by_mode: Mapping[str, Mapping[int, float]]
    split_by_task: Mapping[int, str]
    cold_user_count: Mapping[str, int]
    cold_item_count: Mapping[str, int]
    task_count: int
    adapter_version: str = A_P0_PREDICTIONS_ADAPTER_VERSION

    def select(self, mode: str) -> Mapping[int, float]:
        if mode not in self.rows_by_mode:
            raise BaselinePredictionsError("baseline_mode_missing")
        return self.rows_by_mode[mode]

    def safe_summary(self) -> dict[str, Any]:
        return {
            "adapter_version": self.adapter_version,
            "table_sha256": self.raw_sha256,
            "task_count": self.task_count,
            "modes": list(BASELINE_MODES),
            "coverage_by_mode": {
                mode: len(self.rows_by_mode[mode]) for mode in BASELINE_MODES
            },
            "cold_user_count": dict(self.cold_user_count),
            "cold_item_count": dict(self.cold_item_count),
            "source_verification": "A-declared prediction table; values shape-checked",
        }


def parse_baseline_predictions_bytes(
    payload: bytes | bytearray | str,
) -> BaselinePredictionTable:
    loaded = load_jsonl_bytes(
        payload,
        max_bytes=MAX_BASELINE_BYTES,
        max_rows=MAX_BASELINE_ROWS,
    )
    if not loaded.valid:
        raise BaselinePredictionsError(loaded.code or "baseline_invalid")
    rows_by_mode: dict[str, dict[int, float]] = {
        mode: {} for mode in BASELINE_MODES
    }
    split_by_task: dict[int, str] = {}
    cold_user: dict[str, int] = {mode: 0 for mode in BASELINE_MODES}
    cold_item: dict[str, int] = {mode: 0 for mode in BASELINE_MODES}
    errors: list[str] = []
    for row in loaded.rows:
        if not isinstance(row, dict):
            errors.append("baseline_row_invalid")
            continue
        for role in sorted(exact_keys(row, _FIELDS, code="baseline_schema")):
            errors.append(f"baseline_{role}")
        index = row.get("task_index")
        split = row.get("split")
        mode = row.get("mode")
        prediction = row.get("prediction")
        user_cold = row.get("user_cold_start")
        item_cold = row.get("item_cold_start")
        if type(index) is not int or not 0 <= index < 500:
            errors.append("baseline_task_index_invalid")
            continue
        if split not in SPLITS:
            errors.append("baseline_split_invalid")
            continue
        if mode not in BASELINE_MODES:
            errors.append("baseline_mode_invalid")
            continue
        value = finite_number(prediction)
        if value is None or not 1.0 <= value <= 5.0:
            errors.append("baseline_prediction_invalid")
            continue
        if type(user_cold) is not bool or type(item_cold) is not bool:
            errors.append("baseline_cold_flag_invalid")
            continue
        if index in rows_by_mode[mode]:
            errors.append("baseline_duplicate_prediction")
            continue
        if index in split_by_task and split_by_task[index] != split:
            errors.append("baseline_split_conflict")
            continue
        split_by_task[index] = split
        rows_by_mode[mode][index] = value
        cold_user[mode] += int(user_cold)
        cold_item[mode] += int(item_cold)
    if errors:
        raise BaselinePredictionsError("baseline_invalid", errors)

    index_sets = {mode: set(rows_by_mode[mode]) for mode in BASELINE_MODES}
    if len({frozenset(values) for values in index_sets.values()}) != 1:
        raise BaselinePredictionsError("baseline_mode_task_set_mismatch")
    task_count = len(index_sets[BASELINE_MODES[0]])
    if task_count == 0:
        raise BaselinePredictionsError("baseline_empty")
    raw = payload.encode("utf-8") if isinstance(payload, str) else bytes(payload)
    return BaselinePredictionTable(
        raw_sha256=sha256_bytes(raw),
        rows_by_mode=deep_freeze(
            {mode: dict(rows_by_mode[mode]) for mode in BASELINE_MODES}
        ),
        split_by_task=deep_freeze(dict(split_by_task)),
        cold_user_count=deep_freeze(cold_user),
        cold_item_count=deep_freeze(cold_item),
        task_count=task_count,
    )
